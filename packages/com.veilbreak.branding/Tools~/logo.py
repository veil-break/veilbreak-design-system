#!/usr/bin/env python3
"""Write the mark the games show: Runtime/Vectors/Mark.svg, the slash-cut mark in its final broken pose.

The source is Tools~/source/veilbreak-mark-dark.svg (the dark-ground mark; veilbreak-mark.svg is the light-ground
variant). Unity's SVG importer does not resolve <use>, so the pink and teal ghosts and the ink copy are written out
as groups.

    uv run --frozen python Tools~/logo.py            # write the output
    uv run --frozen python Tools~/logo.py --check    # name a stale output and exit 1, writing nothing
"""

import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
SOURCE = PACKAGE / 'Tools~' / 'source' / 'veilbreak-mark-dark.svg'
OUTPUT = PACKAGE / 'Runtime' / 'Vectors' / 'Mark.svg'


def mark(source):
    """The dark-ground mark with its <use> copies expanded: ghosts first, then the ink."""
    text = source.read_text()
    view = re.search(r'viewBox="([^"]+)" width="([^"]+)" height="([^"]+)"', text)
    body = re.search(r'<g id="mark">(.*)</g>\s*</defs>', text, re.S).group(1)
    box, width, height = view.groups()
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}" width="{width}" height="{height}">',
        '<!-- generated by com.veilbreak.branding Tools~/logo.py from Tools~/source/veilbreak-mark-dark.svg -->',
    ]
    for use in re.finditer(r'<use href="#mark"([^/]*)/>', text):
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', use.group(1)))
        shift = f' transform="translate({attrs["x"]} 0)"' if 'x' in attrs else ''
        opacity = f' fill-opacity="{attrs["opacity"]}"' if 'opacity' in attrs else ''
        out.append(f'<g{shift} fill="{attrs["fill"]}"{opacity}>{body}</g>')
    out.append('</svg>')
    return '\n'.join(out) + '\n'


def main():
    text = mark(SOURCE)
    if OUTPUT.exists() and OUTPUT.read_text() == text:
        return 0
    if '--check' in sys.argv:
        print(f'stale: {OUTPUT.relative_to(PACKAGE)}')
        return 1
    OUTPUT.write_text(text)
    print(f'wrote: {OUTPUT.relative_to(PACKAGE)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
