#!/usr/bin/env python3
"""Generate the package's token outputs from Tokens~/tokens.json, the Veilbreak design tokens this package owns.

Outputs: Runtime/Styles/Tokens.uss (every UI Toolkit-readable token; the high-contrast theme as the .vb-contrast class),
Runtime/Styles/TokensContrast.uss (the same contrast overrides on :root, for VeilbreakGuiContrast.tss)
Runtime/Core/VbTokens.cs (veil-theme colours for code that cannot read USS: rich text, meshes, materials)
and Documentation~/tokens.md (the reference: every token with its value, USS variable, C# name and usage).

    uv run --frozen python Tools~/tokens.py                      # write every output
    uv run --frozen python Tools~/tokens.py --check
    # Name stale outputs and exit 1.
    uv run --frozen python Tools~/tokens.py --upstream FILE
    # Compare another token source.

Every family is {"tokens": [{"name", "value", "usage"}]}; colours carry one value per theme ("veil" first, then
"contrast") or one value for both, and may alias another colour as "{name}". Naming follows the Veilbreak `vb tokens`
generator: colours are --vb-color-<name>, every other token --vb-<name>, type styles --vb-font-size-/line-height-/
tracking-<style>, font files --vb-font-<family>-<weight> (display, body, hud × regular … bold) for
-unity-font-definition. Tokens.json started as a copy of veilbreak/design-system/tokens.json (Veilbreak design system,
https://claude.ai/artifact/LTRBeF1pXxtvxb3MjeaMjC); this package is now its source and the artifact is rebuilt from it.
"""

import argparse
import json
import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
SOURCE = PACKAGE / 'Tokens~' / 'tokens.json'
USS = PACKAGE / 'Runtime' / 'Styles' / 'Tokens.uss'
CONTRAST = PACKAGE / 'Runtime' / 'Styles' / 'TokensContrast.uss'
CS = PACKAGE / 'Runtime' / 'Core' / 'VbTokens.cs'
REFERENCE = PACKAGE / 'Documentation~' / 'tokens.md'
HEADER = 'Generated by Tools~/tokens.py from Tokens~/tokens.json (Veilbreak design tokens). Do not edit.'
# Families whose values UI Toolkit can hold in a custom property: px lengths, plain numbers and ms durations.
USS_FAMILIES = ('spacing', 'layout', 'cut', 'size', 'stroke', 'fx', 'opacity', 'duration')

T = json.loads(SOURCE.read_text())
FLUID = json.loads((PACKAGE / 'Tokens~' / 'fluid.json').read_text())
THEMES = [t['id'] for t in T['color']['themes']]
COLORS = {t['name']: t['value'] for t in T['color']['tokens']}


def colour(name, theme, seen=()):
    value = COLORS[name]
    value = value.get(theme, value[THEMES[0]]) if isinstance(value, dict) else value
    if value.startswith('{'):
        alias = value[1:-1]
        if alias in seen:
            raise ValueError('alias cycle at ' + name)
        return colour(alias, theme, (*seen, name))
    return value


def rgba(value):
    m = re.fullmatch(r'#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?', value)
    if not m:
        raise ValueError('colour tokens are #rrggbb or #rrggbbaa: ' + value)
    r, g, b = (int(m[1][i : i + 2], 16) for i in (0, 2, 4))
    return r, g, b, int(m[2] or 'ff', 16)


def uss_colour(value):
    """USS takes #rrggbb and rgba(); 8-digit hex becomes rgba()."""
    r, g, b, a = rgba(value)
    return value.lower() if a == 255 else f'rgba({r}, {g}, {b}, {round(a / 255, 3):g})'


WEIGHTS = {'400': 'regular', '500': 'medium', '600': 'semibold', '700': 'bold'}


def fonts():
    """(variable, file) per font file: the family key is the one whose stack starts with that family name."""
    keys = {stack.split(',')[0].strip().strip('"'): key for key, stack in T['type']['families'].items()}
    for f in T['type']['fonts']:
        yield f'{keys[f["family"]]}-{WEIGHTS[f["weight"]]}', Path(f['file']).name


def family(key):
    return [(t['name'], str(t['value'])) for t in T.get(key, {}).get('tokens', [])]


def styles():
    for group in T['type']['groups']:
        for s in group['styles']:
            size = float(s['fontSize'].rstrip('px'))
            track = s.get('letterSpacing', '0em')
            track_px = float(track[:-2]) * size if track.endswith('em') else float(track.rstrip('px') or 0)
            yield s['name'], s, round(track_px, 2)


def uss():
    lines = [f'/* {HEADER} */', ':root {']
    lines += [f'    --vb-color-{n}: {uss_colour(colour(n, THEMES[0]))};' for n in COLORS]
    for key in USS_FAMILIES:
        lines += [f'    --vb-{n}: {v};' for n, v in family(key) if re.fullmatch(r'-?[\d.]+(px|ms)?', v)]
    lines += [f'    --vb-font-{n}: url("../Fonts/{file}");' for n, file in fonts()]
    for name, style, track in styles():
        lines += [
            f'    --vb-font-size-{name}: {style["fontSize"]};',
            f'    --vb-line-height-{name}: {style["lineHeight"]};',
            f'    --vb-tracking-{name}: {track:g}px;',
        ]
    # The fluid scale's baseline (Tools~/fluid.py writes the per-width steps): the size ladder and the heading trims.
    lines += [f'    --vb-fs-{n}: {n}px;' for n in FLUID['ladder']]
    for name, style, _ in styles():
        if name.startswith('heading'):
            lines.append(f'    --vb-trim-{name}: {-round(float(style["fontSize"].rstrip("px")) * 0.17, 2):g}px;')
    lines.append('}')
    for theme in THEMES[1:]:
        lines += [f'.vb-{theme} {{', *overrides(theme), '}']
    return '\n'.join(lines) + '\n'


def overrides(theme):
    changed = [n for n in COLORS if colour(n, theme) != colour(n, THEMES[0])]
    return [f'    --vb-color-{n}: {uss_colour(colour(n, theme))};' for n in changed]


def contrast_uss():
    return '\n'.join([f'/* {HEADER} The contrast theme on :root. */', ':root {', *overrides('contrast'), '}']) + '\n'


def pascal(name):
    return ''.join(part[:1].upper() + part[1:] for part in name.split('-'))


CS_TEMPLATE = """// {header}
using UnityEngine;
namespace Veilbreak.Gui {{
/// <summary>Veil-theme colour tokens for code that cannot read USS (rich text, meshes, materials).
/// USS reads the same values as <c>var(--vb-color-*)</c>.</summary>
public static class VbTokens {{
{fields}
 /// <summary>Kit accent for an operative id; <see cref="Text"/> for an unknown id.</summary>
 public static Color Kit(string id)=>id switch{{{kits}_=>Text}};
 /// <summary>#rrggbb, or #rrggbbaa when translucent, for rich-text colour tags.</summary>
 public static string Hex(Color c)=>"#"+(c.a<1?ColorUtility.ToHtmlStringRGBA(c):ColorUtility.ToHtmlStringRGB(c))
  .ToLowerInvariant();
}}
}}
"""


def cs():
    fields = []
    for name in COLORS:
        r, g, b, a = rgba(colour(name, THEMES[0]))
        fields.append(f' public static readonly Color {pascal(name)}=new Color32({r},{g},{b},{a});')
    for name, value in family('duration'):
        fields.append(f' public const int {pascal(name)}={int(value.removesuffix("ms"))};')
    for name, value in family('fx'):
        if name == 'chroma-offset':
            fields.append(f' public const float ChromaOffset={float(value.removesuffix("px")):g}f;')
    kits = ''.join(f'"{n[4:]}"=>{pascal(n)},' for n in COLORS if n.startswith('kit-'))
    return CS_TEMPLATE.format(header=HEADER, fields='\n'.join(fields), kits=kits)


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def reference():
    out = [
        f'<!-- {HEADER} -->',
        '# Token reference',
        '',
        (
            f'Every design token in `Tokens~/tokens.json` ({T["name"]} v{T["version"]}). USS reads a token as'
            ' `var(--vb-…)` anywhere, custom shape properties and `-unity-font-definition` included; code reads'
            ' colours from `VbTokens`. A token marked *reference* has a CSS-only value (shadows, filters, curves) that'
            ' UI Toolkit cannot hold; components apply its intent directly and the web mirror uses it as is. How to'
            ' use them: [platforms](guidelines/05-platforms.md).'
        ),
        '',
        '## Colour',
        '',
        T['color'].get('note', ''),
        '',
        '| Token | ' + ' | '.join(t['name'] for t in T['color']['themes']) + ' | USS | C# | Usage |',
        '| --- | ' + ' | '.join('---' for _ in THEMES) + ' | --- | --- | --- |',
    ]
    for t in T['color']['tokens']:
        n = t['name']
        values = ' | '.join(f'`{colour(n, theme)}`' for theme in THEMES)
        alias = t['value'] if isinstance(t['value'], str) and t['value'].startswith('{') else ''
        usage = (f'Alias of `{alias[1:-1]}`. ' if alias else '') + t.get('usage', '')
        out.append(f'| `{n}` | {values} | `--vb-color-{n}` | `VbTokens.{pascal(n)}` | {cell(usage)} |')
    out += ['', '## Type', '', '| Font file | USS |', '| --- | --- |']
    out += [f'| `Runtime/Fonts/{file}` | `--vb-font-{n}` |' for n, file in fonts()]
    for group in T['type']['groups']:
        out += ['', f'### {group["name"]} ({group["family"]})', '', group.get('note', ''), '']
        out += ['| Style | Size / line | Weight | Tracking | Sample | Usage |', '| --- | --- | --- | --- | --- | --- |']
        for s in group['styles']:
            track = next(t for name, _, t in styles() if name == s['name'])
            out.append(
                f'| `{s["name"]}` | {s["fontSize"]} / {s["lineHeight"]} | {s.get("fontWeight", "")} |'
                f' {s.get("letterSpacing", "0")} ({track:g}px) | {cell(s.get("sample", ""))} |'
                f' {cell(s.get("usage", ""))} |'
            )
    out += [
        '',
        (
            'Each style is `--vb-font-size-<style>`, `--vb-line-height-<style>` and `--vb-tracking-<style>` (px).'
            ' TextCore reads `letter-spacing` in hundredths of an em (`18px` ≈ 0.18em), so Gui.uss writes tracking'
            ' per rule; the `vb-t-*` classes (display, title, label, body, caption, num, badge, power, ally, enemy)'
            ' carry the common combinations.'
        ),
    ]
    for key in (k for k, v in T.items() if isinstance(v, dict) and 'tokens' in v and k != 'color'):
        out += ['', f'## {key.capitalize()}', '']
        if T[key].get('note'):
            out += [T[key]['note'], '']
        out += ['| Token | Value | USS | Usage |', '| --- | --- | --- | --- |']
        for t in T[key]['tokens']:
            value = str(t['value'])
            uss_name = (
                f'`--vb-{t["name"]}`'
                if key in USS_FAMILIES and re.fullmatch(r'-?[\d.]+(px|ms)?', value)
                else '*reference*'
            )
            out.append(f'| `{t["name"]}` | `{cell(value)}` | {uss_name} | {cell(t.get("usage", ""))} |')
    return '\n'.join(out) + '\n'


def upstream(path):
    other = {t['name']: t['value'] for t in json.loads(Path(path).read_text())['color']['tokens']}
    for name in sorted(set(COLORS) | set(other)):
        if COLORS.get(name) != other.get(name):
            print(f'{name}: package {COLORS.get(name)!r} upstream {other.get(name)!r}')


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true', help='report stale outputs and exit 1 without writing')
    parser.add_argument('--upstream', metavar='FILE', help='compare colour tokens with another tokens.json')
    args = parser.parse_args()
    if args.upstream:
        upstream(args.upstream)
        return
    outputs = ((USS, uss()), (CONTRAST, contrast_uss()), (CS, cs()), (REFERENCE, reference()))
    stale = [path for path, text in outputs if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            print('stale:', path.relative_to(PACKAGE))
        sys.exit(1 if stale else 0)
    for path, text in outputs:
        path.write_text(text)
    print('wrote', ', '.join(str(path.relative_to(PACKAGE)) for path, _ in outputs))


if __name__ == '__main__':
    main()
