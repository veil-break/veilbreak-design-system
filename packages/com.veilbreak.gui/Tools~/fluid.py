#!/usr/bin/env python3
"""Generate the fluid scale from Tokens~/fluid.json and Tokens~/tokens.json.

Outputs: Runtime/Styles/Fluid.uss (one `.vb-fluid-<width>` class per step, each overriding every
type size, spacing and layout token and the font-size ladder `--vb-fs-<n>` with its value times the step's factor) and
Runtime/Core/VbFluidSteps.cs (the same steps and factors for `VbFluid`, which picks the class from a panel width).

    uv run --frozen python Tools~/fluid.py            # write
    uv run --frozen python Tools~/fluid.py --check    # name stale outputs and exit 1
"""

import json
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
FLUID = json.loads((PACKAGE / 'Tokens~' / 'fluid.json').read_text())
TOKENS = json.loads((PACKAGE / 'Tokens~' / 'tokens.json').read_text())
USS = PACKAGE / 'Runtime' / 'Styles' / 'Fluid.uss'
CS = PACKAGE / 'Runtime' / 'Core' / 'VbFluidSteps.cs'
HEADER = 'Generated by Tools~/fluid.py from Tokens~/fluid.json and tokens.json. Do not edit.'


def factor(width):
    """Piecewise linear through the factors' anchors, flat outside them."""
    anchors = sorted((int(k), v) for k, v in FLUID['factors'].items())
    if width <= anchors[0][0]:
        return anchors[0][1]
    for (w0, f0), (w1, f1) in zip(anchors, anchors[1:]):
        if width <= w1:
            return f0 + (f1 - f0) * (width - w0) / (w1 - w0)
    return anchors[-1][1]


def px(value):
    return float(value.removesuffix('px'))


def scaled():
    """(name, baseline px) for every token the scale moves."""
    items = []
    for group in TOKENS['type']['groups']:
        items += [(f'font-size-{s["name"]}', px(s['fontSize'])) for s in group['styles']]
    for key in ('spacing', 'layout'):
        items += [(t['name'], px(t['value'])) for t in TOKENS[key]['tokens']]
    items += [(f'fs-{n}', float(n)) for n in FLUID['ladder']]
    # UI Toolkit has no line-height: a 0.9 heading trims the surplus leading (0.17em a side) with a negative margin.
    for group in TOKENS['type']['groups']:
        for s in group['styles']:
            if s['name'].startswith('heading'):
                items.append((f'trim-{s["name"]}', -round(px(s['fontSize']) * 0.17, 2)))
    return items


def number(value):
    return f'{value:.2f}'.rstrip('0').rstrip('.')


def uss():
    items = scaled()
    out = [f'/* {HEADER} The baseline (factor 1) is on :root in Tokens.uss. */']
    for step in FLUID['steps']:
        f = factor(step)
        out.append(f'.vb-fluid-{step} {{ /* ×{f:.3f} */')
        out += [f'    --vb-{n}: {number(v * f)}px;' for n, v in items]
        out.append('}')
    return '\n'.join(out) + '\n'


def cs():
    steps = ','.join(str(s) for s in FLUID['steps'])
    factors = ','.join(f'{factor(s):.4f}f' for s in FLUID['steps'])
    return (
        f'// {HEADER}\n'
        'namespace Veilbreak.Gui {\n'
        'public static partial class VbFluid {\n'
        f' /// <summary>The widths that have a step (class <c>vb-fluid-&lt;w&gt;</c>), and the factors.</summary>\n'
        f' public static readonly int[] Steps={{{steps}}};\n'
        f' public static readonly float[] Factors={{{factors}}};\n'
        f' public const int Reference={FLUID["reference"]};\n'
        '}\n'
        '}\n'
    )


def main():
    outputs = ((USS, uss()), (CS, cs()))
    stale = [p for p, text in outputs if not p.exists() or p.read_text() != text]
    if '--check' in sys.argv:
        for p in stale:
            print('stale:', p.relative_to(PACKAGE))
        sys.exit(1 if stale else 0)
    for p, text in outputs:
        p.write_text(text)
    print('wrote', ', '.join(str(p.relative_to(PACKAGE)) for p, _ in outputs))


if __name__ == '__main__':
    main()
