def emulate_styles(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    output, cursor = [], 0
    while True:
        start = text.find('{', cursor)
        if start < 0:
            break
        end = block_end(text, start)
        selector, body = text[cursor:start].strip(), text[start + 1:end]
        if selector.startswith(('@media', '@supports', '@layer')):
            nested = emulate_styles(body)
            if nested:
                output.append(selector + ' {\n' + nested + '\n}')
        elif not selector.startswith('@'):
            selectors = []
            for part in split_top(selector, ','):
                if not re.search(state, part):
                    continue
                part = re.sub(state, lambda m: '[data-inspect-' + m[1] + ']', part)
                pseudo = re.search(r'::(?:before|after)\b', part)
                position = pseudo.start() if pseudo else len(part)
                selectors.append(part[:position] + ':where([data-inspect-node])' + part[position:])
            if selectors:
                output.append(', '.join(selectors) + ' {' + body + '}')
        cursor = end + 1
    return '\n'.join(output)

