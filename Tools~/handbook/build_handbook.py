def class_body(name):
    for path, text in SRC.items():
        m = re.search(r'(?:\[UxmlElement\]\s*)?public\s+(?:sealed\s+|static\s+|abstract\s+)*(?:partial\s+)?(class|struct|enum)\s+' + re.escape(name) + r'\b([^{]*)\{', text)
        if not m:
            continue
        i, depth = m.end(), 1
        while depth and i < len(text):
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        return path, m.group(1), m.group(2).strip(), text[m.end():i - 1], text[max(0, m.start() - 4000):m.start()]
    return None


def api_for(name):
    found = class_body(name)
    if not found:
        return None
    path, kind, base, body, before = found
    doc = []
    for ln in reversed(before.rstrip().split('\n')):
        ln = ln.strip()
        if ln.startswith('///'):
            doc.insert(0, ln[3:].strip())
        elif ln.startswith('[') or not ln:
            continue
        else:
            break
    summary = re.sub(r'<see cref="([^"]+)"\s*/>', r'\1', ' '.join(doc))
    summary = re.sub(r'<c>(.*?)</c>', r'\1', summary)
    summary = re.sub(r'</?[a-z]+[^>]*>', '', summary).replace('&lt;', '<').replace('&gt;', '>').strip()
    members, depth, buf, i = [], 0, '', 0
    # Top-level statements of the class body only.
    while i < len(body):
        c = body[i]
        if depth == 0:
            buf += c
            if c in '{;' or body.startswith('=>', i):
                stmt = ' '.join(buf.split())
                if body.startswith('=>', i):
                    stmt = stmt[:-1] if stmt.endswith('=') else stmt
                members.append(stmt.rstrip('{;= ').strip())
                buf = ''
                if c == '{':
                    depth = 1
                elif body.startswith('=>', i):
                    j = body.find(';', i)
                    k = body.find('{', i)
                    if k != -1 and (j == -1 or k < j):
                        depth, i = 1, k
                    else:
                        i = j
        else:
            depth += {'{': 1, '}': -1}.get(c, 0)
            if depth == 0:
                pass
        i += 1
    out = []
    for m in members:
        m = re.sub(r'^(\[[^\]]*\]\s*)*', lambda x: '[UxmlAttribute] ' if 'UxmlAttribute' in x.group(0) else '', m)
        if not re.search(r'(^|\s)public\s', m) or 'class ' in m:
            continue
        m = re.sub(r'\bpublic\s+', '', m).strip()
        if kind == 'enum':
            continue
        out.append(m[:220])
    if kind == 'enum':
        out = ['enum ' + name + ' { ' + ' '.join(body.split()) + ' }']
    return {'type': name, 'kind': kind, 'base': base.lstrip(':').strip(), 'file': str(path.relative_to(PKG)), 'summary': summary, 'members': out}


# ── 7. components.md sections ────────────────────────────────────────────────
DOC = (PKG / 'Documentation~' / 'components.md').read_text()


def doc_section(title):
    lines, out, level = DOC.split('\n'), None, None
    for ln in lines:
        m = re.match(r'^(#{2,3})\s+(.*)$', ln)
        if m and out is not None and len(m.group(1)) <= level:
            break
        if m and m.group(2).strip() == title:
            out, level = [], len(m.group(1))
            continue
        if out is not None:
            out.append(ln)
    return '\n'.join(out).strip() if out else None


def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r'`([^`]+)`', r'<code>\1</code>', t)
    t = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', t)
    t = re.sub(r'(?<![\w*])\*([^*\s][^*]*)\*(?!\w)', r'<em>\1</em>', t)
    t = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'<span>\1</span>', t)
    return t


def md(text):
    if not text:
        return ''
    out, lines, i = [], text.split('\n'), 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith('```'):
            j = i + 1
            while j < len(lines) and not lines[j].startswith('```'):
                j += 1
            out.append('<pre tabindex="0" role="region" aria-label="Code example"><code>' + html.escape('\n'.join(lines[i + 1:j])) + '</code></pre>')
            i = j + 1
            continue
        if ln.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'):
                if not re.match(r'^\|\s*-', lines[i]):
                    rows.append([c.strip() for c in lines[i].strip().strip('|').split('|')])
                i += 1
            t = '<div data-content="table" tabindex="0" role="region" aria-label="Reference table"><table><thead><tr>' + ''.join(f'<th scope="col">{inline(c)}</th>' for c in rows[0]) + '</tr></thead><tbody>'
            t += ''.join('<tr>' + ''.join(f'<td>{inline(c)}</td>' for c in r) + '</tr>' for r in rows[1:]) + '</tbody></table></div>'
            out.append(t)
            continue
        if re.match(r'^\s*- ', ln):
            items = []
            while i < len(lines) and (re.match(r'^\s*- ', lines[i]) or (lines[i].startswith('  ') and lines[i].strip())):
                if re.match(r'^\s*- ', lines[i]):
                    items.append([len(lines[i]) - len(lines[i].lstrip()), lines[i].strip()[2:]])
                else:
                    items[-1][1] += ' ' + lines[i].strip()
                i += 1
            # Child lists belong inside their parent list item, never beside it.
            nodes, stack = [], []
            for indent, text in items:
                node = {'text': text, 'children': []}
                while stack and indent <= stack[-1][0]:
                    stack.pop()
                (stack[-1][1]['children'] if stack else nodes).append(node)
                stack.append((indent, node))

            def render_list(nodes):
                return '<ul>' + ''.join('<li>' + inline(n['text']) +
                    (render_list(n['children']) if n['children'] else '') + '</li>' for n in nodes) + '</ul>'

            out.append(render_list(nodes))
            continue
        m = re.match(r'^(#{2,4})\s+(.*)', ln)
        if m:
            level = len(m.group(1))
            out.append(f'<h{level}>{inline(m.group(2))}</h{level}>')
            i += 1
            continue
        if ln.strip() == '---' or not ln.strip():
            i += 1
            continue
        para = [ln]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r'^(\s*- |\||```|#)', lines[i]):
            para.append(lines[i])
            i += 1
        out.append('<p>' + inline(' '.join(para)) + '</p>')
    return '\n'.join(out)


